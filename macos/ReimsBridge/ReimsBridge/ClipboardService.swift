import AppKit
import Foundation

struct ClipboardMetadata {
    let changeCount: Int
    let hasPlainText: Bool
    let isExcluded: Bool
}

enum ClipboardError: LocalizedError {
    case noText
    case excluded
    case oversized
    case embeddedNul
    case changedDuringRead
    case changedDuringWrite
    case writeFailed
    case testFailed
    
    var errorDescription: String? {
        switch self {
        case .noText:
            return "Clipboard containes no plain text"
        case .excluded:
            return "Clipboard content is marked as excluded"
        case .oversized:
            return "Clipboard exceeds size limit"
        case .embeddedNul:
            return "Clipboard contains embedded NUL"
        case .changedDuringRead:
            return "Clipboard changed during read"
        case .changedDuringWrite:
            return "Clipboard changed during write verification"
        case .writeFailed:
            return "Clipboard write failed"
        case .testFailed:
            return "Clipboard self-test failed"
        }
    }
}

@MainActor
enum ClipboardService {
    static let maxClipboardBytes = 1024 * 1024
    
    private static let excludedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword"
    ]
    
    static func inspect(
        _ pasteboard: NSPasteboard = .general
    ) -> ClipboardMetadata {
        let types = pasteboard.types ?? []
        
        return ClipboardMetadata(changeCount: pasteboard.changeCount, hasPlainText: types.contains(.string), isExcluded: types.contains {
            excludedTypes.contains($0.rawValue)
        })
    }
    
    static func validate(_ text: String) throws {
        guard !text.isEmpty else {
            throw ClipboardError.noText
        }
        
        guard text.utf8.count <= maxClipboardBytes else {
            throw ClipboardError.oversized
        }
        
        guard !text.utf8.contains(0) else {
            throw ClipboardError.embeddedNul
        }
    }
    
    static func readText(
        _ pasteboard: NSPasteboard = .general,
        respectPrivacyMarkers: Bool = false,
        expectedChangeCount: Int? = nil
    ) throws -> String {
        let initialCount = pasteboard.changeCount
        if let expectedChangeCount, expectedChangeCount != initialCount {
            throw ClipboardError.changedDuringRead
        }

        let metadata = inspect(pasteboard)
        
        guard !respectPrivacyMarkers || !metadata.isExcluded else {
            throw ClipboardError.excluded
        }
        
        guard metadata.hasPlainText else {
            throw ClipboardError.noText
        }
        
        guard pasteboard.changeCount == initialCount else {
            throw ClipboardError.changedDuringRead
        }
        
        guard let text = pasteboard.string(forType: .string) else {
            throw ClipboardError.noText
        }
        
        guard pasteboard.changeCount == initialCount else {
            throw ClipboardError.changedDuringRead
        }
        
        try validate(text)
        
        return text
    }
    
    static func writeTextChecked(
        _ text: String,
        to pasteboard: NSPasteboard = .general,
        expectedChangeCount: Int? = nil
    ) throws -> Int? {
        try validate(text)

        let item = NSPasteboardItem()

        guard item.setString(text, forType: .string) else {
            throw ClipboardError.writeFailed
        }

        if let expectedChangeCount,
           pasteboard.changeCount != expectedChangeCount {
            return nil
        }

        let ownedCount = pasteboard.clearContents()

        guard pasteboard.changeCount == ownedCount else {
            throw ClipboardError.changedDuringWrite
        }

        guard pasteboard.writeObjects([item]) else {
            throw ClipboardError.writeFailed
        }

        guard pasteboard.changeCount == ownedCount else {
            throw ClipboardError.changedDuringWrite
        }

        guard let received = pasteboard.string(forType: .string),
              received.utf8.elementsEqual(text.utf8) else {
            throw ClipboardError.changedDuringWrite
        }

        guard pasteboard.changeCount == ownedCount else {
            throw ClipboardError.changedDuringWrite
        }

        return ownedCount
    }

    static func writeText(
        _ text: String,
        to pasteboard: NSPasteboard = .general
    ) throws {
        _ = try writeTextChecked(text, to: pasteboard)
    }
    
    static func selfTest() throws -> Int {
        let pasteboard = NSPasteboard.withUniqueName()
        
        defer {
            pasteboard.releaseGlobally()
        }
        
        let fixture =
            "ReimsBridge M2.1\r\n" +
            "Árviztűrő tükörfúrógép\r\n" +
            "🚀 🦀 🍎\n" +
            "\tTabbed code\n" +
            "   Indented code\n" +
            "Trailing spaces \n"
        
        let initialCount = pasteboard.changeCount

        guard let writtenCount = try writeTextChecked(
            fixture,
            to: pasteboard,
            expectedChangeCount: initialCount
        ) else {
            throw ClipboardError.testFailed
        }

        guard writtenCount != initialCount,
              pasteboard.changeCount == writtenCount else {
            throw ClipboardError.testFailed
        }

        print("[CLIPBOARD] Initial change count: \(initialCount)")
        print("[CLIPBOARD] Written change count: \(writtenCount)")
        print("[CLIPBOARD] Observed change count: \(pasteboard.changeCount)")
        print("[CLIPBOARD] Current-count write: PASS")
        print("[CLIPBOARD] Write count attribution: PASS")

        let received = try readText(pasteboard)

        guard received.utf8.elementsEqual(fixture.utf8) else {
            throw ClipboardError.testFailed
        }

        let rejected = try writeTextChecked(
            "This must never reach the pasteboard",
            to: pasteboard,
            expectedChangeCount: initialCount
        )

        guard rejected == nil else {
            throw ClipboardError.testFailed
        }

        guard pasteboard.changeCount == writtenCount else {
            throw ClipboardError.testFailed
        }

        let preservedAfterRejection = try readText(pasteboard)

        guard preservedAfterRejection.utf8.elementsEqual(fixture.utf8) else {
            throw ClipboardError.testFailed
        }

        print("[CLIPBOARD] Stale conditional write rejected: PASS")
        print("[CLIPBOARD] Destination preservation: PASS")

        let secondFixture = "Conditional macOS write 🚀\r\n"

        guard let secondCount = try writeTextChecked(
            secondFixture,
            to: pasteboard,
            expectedChangeCount: writtenCount
        ) else {
            throw ClipboardError.testFailed
        }

        guard secondCount != writtenCount,
              pasteboard.changeCount == secondCount else {
            throw ClipboardError.testFailed
        }

        let secondReceived = try readText(pasteboard)

        guard secondReceived.utf8.elementsEqual(secondFixture.utf8) else {
            throw ClipboardError.testFailed
        }

        print("[CLIPBOARD] Subsequent conditional write: PASS")

        try writeText(fixture, to: pasteboard)

        let countBeforeInvalidWrites = pasteboard.changeCount
        let invalidInputs = [
            "",
            "Hello\0World",
            String(repeating: "x", count: maxClipboardBytes + 1)
        ]
        
        for input in invalidInputs {
            do {
                try writeText(input, to: pasteboard)
                throw ClipboardError.testFailed
            } catch ClipboardError.noText {
                continue
            } catch ClipboardError.embeddedNul {
                continue
            } catch ClipboardError.oversized {
                continue
            }
        }
        
        let preserved = try readText(pasteboard)

        guard preserved.utf8.elementsEqual(fixture.utf8),
              pasteboard.changeCount == countBeforeInvalidWrites else {
            throw ClipboardError.testFailed
        }

        print("[CLIPBOARD] Invalid write preservation: PASS")
        print("[CLIPBOARD] All counter-aware write tests: PASS")
        
        for marker in excludedTypes {
            let item = NSPasteboardItem()
            
            guard item.setString("Synthetic test", forType: .string),
                  item.setData(Data(), forType: NSPasteboard.PasteboardType(marker)) else {
                throw ClipboardError.testFailed
            }
            
            pasteboard.clearContents()
            
            guard pasteboard.writeObjects([item]) else {
                throw ClipboardError.testFailed
            }
            
            guard inspect(pasteboard).isExcluded else {
                throw ClipboardError.testFailed
            }
            
            let markedText = try readText(pasteboard)

            guard markedText.utf8.elementsEqual("Synthetic test".utf8) else {
                throw ClipboardError.testFailed
            }

            do {
                _ = try readText(
                    pasteboard,
                    respectPrivacyMarkers: true
                )
                throw ClipboardError.testFailed
            } catch ClipboardError.excluded {
                continue
            }
        }
        
        return fixture.utf8.count
    }
}
